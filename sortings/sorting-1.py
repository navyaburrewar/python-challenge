# What is Sorting?

# Sorting means arranging data in a specific order.

# Usually:

# Ascending order → smallest to largest
# Example: [1, 2, 3, 4, 5]
# Descending order → largest to smallest
# Example: [5, 4, 3, 2, 1]

# # Sorting is one of the most important concepts in programming because many operations become faster after sorting:

# # Searching
# # Finding duplicates
# # Data analysis
# # Database operations
# # Ranking systems
# # Organizing records




# ===============Why Do We Need Sorting?==========#

