# ======== merge sort  ============#

# Merge Sort is a divide and conquer algorithm.
# It divides the array into halves, recursively sorts them, and merges the sorted halves.
# Time Complexity: O(n log n)

# ============== algorithm steps===============#

# Divide the array into two equal halves.
# Recursively divide each half until each subarray contains only one element.
# Merge two sorted subarrays into a single sorted array.
# Compare elements from both subarrays while merging.
# Place the smaller element into the merged array.
# Continue until all elements are merged.
# Repeat merging until the complete sorted array is formed.

