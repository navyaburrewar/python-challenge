# What is the Python sys Module?

# The sys module is a built-in Python module that provides tools to:

# ✅ Work with command line arguments
# ✅ Control program execution
# ✅ Access system-specific settings
# ✅ Manage input/output streams
# ✅ Handle memory and recursion limits
# ✅ Exit programs safely

# You don’t need to install it — it comes with Python.


