# Module Definition
# A module is a file containing Python definitions and statements that can be imported and used in another Python program.


#The file must end with:
#.py

# example
#  math.py



# ## Why Do We Use Modules?

# ✅ 1. Organize Code
# You can split a big program into smaller files.

# ✅ 2. Reuse Code
# Write once → Use many times.

# ✅ 3. Avoid Rewriting
# No need to rewrite common functions.

# ✅ 4. Improve Readability
# Cleaner and easier to understand programs.

# ✅ 5. Team Work
# Different people can work on different modules.




# 📦 Types of Modules in Python

# Python modules are mainly of two types:

# 1️⃣ Built-in Modules (Standard Library Modules)
# 2️⃣ User-defined Modules (Custom Modules)



# 1️⃣ Built-in Modules (Standard Library Modules)
# 🧠 What are they?

# These modules are already included with Python.
# You don’t need to install anything — just import and use them.

# They are provided as part of Python’s standard library.




# 🎯 Why they’re useful

# They save time because common tasks are already implemented.

# You can:

# Do math calculations
# Work with dates and time
# Generate random numbers
# Handle files and folders
# Work with system features




# 📚 Common  Built-in Modules


# Module	 What it does
# math   	 Mathematical functions
# random	 Random number generation
# datetime	 Date and time handling
# os	     Interact with operating system
# sys	     Python interpreter features




# 2️⃣ User-defined Modules (Custom Modules)
# 🧠 What are they?

# These are modules created by you (the programmer).

# When your program gets big, you can split it into multiple files.
# Each file becomes a module.



# Why they’re useful

# They help you:
# Organize large programs
# Reuse your own code
# Keep code clean and readable
# Work in teams easily




# 🔄 Extra: Third-Party Modules (Installed Separately)

# These are not built-in and not written by you.

# They are created by other developers and shared online.
# You install them using pip.

# Examples:

# Web development
# Data science
# Machine learning
# Game developmen# 
# # Example libraries:
# # requests (for web requests)
# numpy (for numerical computing)
# pandas (for data analysis)


# #  📦 Installing a Third-party Module

## pip install requests
## import requests



# Quick Comparison

# Feature	      Built-in Modules	    User-defined Modules	      Third-party Modules
# Who makes it?   Python team     	     You	                         Other developers
# Installation	  Already available	    You create it	               Install with pip
# Use case	      Common tasks	        Your project code	         Advanced features





# 📦 Built-in modules → Ready-made tools that come with Python
# 🛠️ User-defined modules → Files you create to organize your code
# 🌍 Third-party modules → External libraries you install for extra features